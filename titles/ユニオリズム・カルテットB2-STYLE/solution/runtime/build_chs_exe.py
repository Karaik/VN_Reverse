def patch_gbk_table(src_exe: Path, out_exe: Path) -> Path:
    sjis_table = make_sjis_table()
    gbk_table = make_gbk_table()
    data = src_exe.read_bytes()
    pos = data.find(sjis_table)
    if pos < 0:
        raise RuntimeError("未找到 Shift-JIS lead byte table")
    out_exe.parent.mkdir(parents=True, exist_ok=True)
    out_exe.write_bytes(data.replace(sjis_table, gbk_table, 1))
    return out_exe

def find_vcvarsall() -> Path:
    vswhere = Path(r"C:\Program Files (x86)\Microsoft Visual Studio\Installer\vswhere.exe")
    if not vswhere.exists():
        raise FileNotFoundError("未找到 vswhere.exe")

    result = subprocess.run(
        [
            str(vswhere),
            "-latest",
            "-products",
            "*",
            "-requires",
            "Microsoft.Component.MSBuild",
            "-property",
            "installationPath",
        ],
        check=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        capture_output=True,
    )
    install_path = result.stdout.strip()
    if not install_path:
        raise FileNotFoundError("未找到 Visual Studio Build Tools")

    vcvarsall = Path(install_path) / "VC" / "Auxiliary" / "Build" / "vcvarsall.bat"
    if not vcvarsall.exists():
        raise FileNotFoundError("未找到 vcvarsall.bat")
    return vcvarsall


def compile_patch_dll(out_dll: Path) -> Path:
    source = RUNTIME_DIR / "src" / "patch_chs.c"
    vcvarsall = find_vcvarsall()

    out_dll.parent.mkdir(parents=True, exist_ok=True)
    bat = out_dll.parent / "build_patch_chs.bat"
    write_text(
        bat,
        "@echo off\n"
        f'call "{vcvarsall}" x86 >nul\n'
        f'cl /nologo /LD /O2 /MT /TP "{source}" /Fe:"{out_dll}" /link user32.lib gdi32.lib\n',
    )
    run_command(["cmd", "/c", str(bat)], cwd=out_dll.parent)
    return out_dll


def build_chs_exe(src_exe: Path, out_dir: Path) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    patch_exe = out_dir / PATCH_EXE_NAME
    patch_dll = out_dir / PATCH_DLL_NAME
    setdll_exe = YURIS_TOOLS_DIR / "setdll.exe"

    with tempfile.TemporaryDirectory(prefix="uqb2s_build_") as temp_root:
        temp_dir = Path(temp_root)
        temp_exe = temp_dir / PATCH_EXE_NAME
        temp_dll = temp_dir / PATCH_DLL_NAME
        temp_setdll = temp_dir / setdll_exe.name

        patch_gbk_table(src_exe, temp_exe)
        compile_patch_dll(temp_dll)
        copy_file(setdll_exe, temp_setdll)
        run_command(
            [
                str(temp_setdll),
                f"/d:{PATCH_DLL_NAME}",
                PATCH_EXE_NAME,
            ],
            cwd=temp_dir,
        )
        shutil.copy2(temp_exe, patch_exe)
        shutil.copy2(temp_dll, patch_dll)
    return patch_exe, patch_dll
